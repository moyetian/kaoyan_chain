# -*- coding: utf-8 -*-
"""
考研苏格拉底式微步骤启发教学技能 (Socratic Scaffolding Tutor Skill)
核心使命：
  1. 彻底解决“看全解吃快餐、以为懂了但自己动不了笔”的假懂陷阱；
  2. 严禁直接剧透终极答案与全过程推导；
  3. 提供三级阶梯式渐进启发 (Level 1 破题定性 ➔ Level 2 首步搭桥 ➔ Level 3 易错陷阱警示)；
  4. 倒逼学员在草稿纸上独立写出关键下一步，培育独立考场应试解题自驱力！
"""

def build_hint_prompt(question_text, hint_level=1, context=""):
    """
    构建苏格拉底式三级启发 Prompt
    hint_level:
      - 1: 破题定性（指出核心考纲定理、母题考点、思维突破口，绝不写公式计算）
      - 2: 首步搭桥（给出关键的首步辅助函数构造、倒数换元或第一项代数变形，把后续计算留给学员）
      - 3: 避坑指引（指出命题人在何处设计了失分陷阱，如分母非零、定义域、绝对值符号讨论）
    """
    level = max(1, min(int(hint_level), 3))
    
    level_guidance = {
        1: (
            "【当前为 Level 1 破题定性提示】：\n"
            "- 明确指出本题属于考纲哪一章节的核心母题（如：导数中值定理、二重积分对称性、矩阵相似对角化、408虚拟内存分页）；\n"
            "- 点明本题的【思维第一突破口】（例如：“观察分子分母极限阶数”、“利用奇偶对称性先消项”、“令被积函数构造辅助函数 F(x)”）；\n"
            "- ⚠️ 【铁律】：绝对不准给出具体的代数变形公式，更严禁给出最终答案！只需指明战略思考方向，并鼓励学员写出第一步试一试。"
        ),
        2: (
            "【当前为 Level 2 首步搭桥提示】：\n"
            "- 假设学员已经尝试了战略方向但仍在推导上卡壳；\n"
            "- 给出解题的【最关键第一步推导】（例如：写出设辅助函数的第一行 $F(x) = ...$，或给出关键拆项式）；\n"
            "- ⚠️ 【铁律】：在此处戛然而止！留出下一步的核心计算（如求导、通分、判定导数零点），提问学员：“第一步已经为你搭好，请你尝试求导看看结果如何？”"
        ),
        3: (
            "【当前为 Level 3 命题避坑指南】：\n"
            "- 假设学员已推导至中后段；\n"
            "- 深度解密命题人设置的【高频失分陷阱】（例如：“注意 $x \\to 0^+$ 与 $x \\to 0^-$ 符号是否一致”、“验证罗尔定理端点闭区间连续开区间可导”、“注意特征向量必须正交化”）；\n"
            "- 提醒学员在草稿纸上规范书写采分点步骤，准备最终自测批改。"
        )
    }

    prompt = f"""你是一位深谙苏格拉底式启发教学理念的考研专属私教总教练。
学员正在攻坚一道考研难题，并请求你给予【第 {level} 级启发性提示】。

【待攻坚题目】：
{question_text.strip()}
"""
    if context:
        prompt += f"\n【学员之前的草稿思路或前置互动】：\n{context.strip()}\n"

    prompt += f"""
【启发要求规范】：
{level_guidance[level]}

请用亲切、严谨且富有启发性的私教语气输出该级别的指导。控制在 150~250 字以内，精炼、直击要害！
"""
    return prompt

def get_next_level(current_level):
    """计算下一次提示级别"""
    lvl = int(current_level)
    return min(lvl + 1, 3)
